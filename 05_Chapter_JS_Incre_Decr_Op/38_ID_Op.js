// Pre Increment
let a = 10;
let b = ++a; // here a is incremented first and then assigned to b, so b will be 11 and a will also be 11
console.log(b);
console.log(a)

/*
# Increment and decrement Operator ( ++, --) 
 Pre and Post 

 let a= 10;

- pre -   ++a ->. Pre
    - **first increase the value by 1, then assign the value.**

- post a++ ->  
    - **First, assign the value, then increment by 1**
    */